import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import {
  ENGINE_VERSION,
  PHOTO_GATE_MODEL,
  SCAM_ENGINE_VERSION,
  VIDEO_FRAMES_MODEL,
} from '@isitreal/core';
import { loadJsonl } from './dataset.js';
import { randomBaseline } from './detectors.js';
import { GATE_SCORES_FILE } from './image-gate-train.js';
import {
  PHOTO_SOURCE,
  evaluateImageModels,
  imageReportMarkdown,
  loadGateScores,
  loadImageScores,
  type ImageModelReport,
} from './image-models.js';
import { FEATURES_FILE, loadFeatureRows } from './features.js';
import { evaluate, toMarkdown, type DetectorReport } from './run.js';
import { evaluateScam, loadScamJsonl, scamToMarkdown, type ScamReport } from './scam.js';
import {
  SAMPLING_VERSIONS,
  evaluateVideoFrames,
  loadVideoScores,
  videoReportMarkdown,
  type VideoReport,
} from './video-models.js';
import {
  SPECS,
  evaluateFitted,
  fitAll,
  leaveOneDomainOut,
  textReportMarkdown,
  type LodoRow,
  type SpecReport,
} from './text-models.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({ options: { alpha: { type: 'string', default: '0.01' } } });
const alpha = Number(values.alpha);
const cache = join(root, 'datasets', '.cache');

const sections: string[] = [
  '# Evaluation report',
  '',
  `Engine ${ENGINE_VERSION}, ${SCAM_ENGINE_VERSION}, alpha = ${alpha}. Generated by \`pnpm eval\`.`,
  '',
];
const json: {
  text: DetectorReport[];
  scam: ScamReport[];
  textModels?: SpecReport[];
  leaveOneDomainOut?: LodoRow[];
  imageModels?: ImageModelReport[];
  imageModelsUngated?: ImageModelReport[];
  videoFrames?: VideoReport;
  videoFramesWatched?: VideoReport;
} = { text: [], scam: [] };

// Harness sanity check on the toy set.
{
  const items = await loadJsonl(join(root, 'datasets', 'toy', 'text.jsonl'));
  const reports = [evaluate(randomBaseline, 'toy', items, alpha)];
  json.text.push(...reports);
  sections.push(toMarkdown(reports));
}

// Text detectors, from the committed feature table (numbers only; no model or texts needed).
if (existsSync(FEATURES_FILE)) {
  const rows = loadFeatureRows();
  const fitted = fitAll(rows);
  const reports = fitted.map((f) => evaluateFitted(f, rows, alpha));
  const lodo = leaveOneDomainOut(
    SPECS.find((s) => s.id.startsWith('text.ensemble'))!,
    rows,
    alpha,
  );
  json.textModels = reports;
  json.leaveOneDomainOut = lodo;
  sections.push(textReportMarkdown(reports, lodo, rows));
}

// Image classifiers, from the committed score tables (numbers only).
{
  const rows = loadImageScores();
  if (rows.length > 0) {
    // 1. Without the photo gate, calibrated on stock-style photos only: shows why a gate is needed.
    const plain = evaluateImageModels(rows, { alpha, calibrationSources: [PHOTO_SOURCE] });
    json.imageModelsUngated = plain;
    sections.push(
      imageReportMarkdown(
        plain,
        alpha,
        'Image classifiers WITHOUT the photo gate (calibrated on stock-style photos)',
      ),
    );
    // 2. As shipped: only photo-like images are judged; calibration uses every kind of non-AI
    // image that passes the gate.
    const gate = loadGateScores(GATE_SCORES_FILE, PHOTO_GATE_MODEL.threshold);
    if (gate !== null) {
      const gated = evaluateImageModels(rows, { alpha, gate });
      json.imageModels = gated;
      sections.push(
        imageReportMarkdown(gated, alpha, 'Image classifiers WITH the photo gate (as shipped)'),
      );
    }
  }
}

// Video frame check, from the committed score tables (numbers only): once for video files and
// once for a video playing in the browser. Each way has its own calibration.
{
  const rows = loadVideoScores();
  const rule = {
    gateThreshold: PHOTO_GATE_MODEL.threshold,
    minChecked: VIDEO_FRAMES_MODEL.minChecked,
  };
  for (const sampling of ['spread', 'watched'] as const) {
    const report = evaluateVideoFrames(rows, rule, alpha, SAMPLING_VERSIONS[sampling]);
    if (report.calibrationSize === 0) continue;
    if (sampling === 'spread') json.videoFrames = report;
    else json.videoFramesWatched = report;
    sections.push(videoReportMarkdown(report, alpha, sampling));
  }
}

// Scam rules.
const scamSets: [string, string][] = [
  ['scam-dev', join(root, 'datasets', 'scam', 'dev.jsonl')],
  ['scam-test (frozen)', join(root, 'datasets', 'scam', 'test.jsonl')],
];
if (existsSync(join(cache, 'sms')))
  scamSets.push(
    ['sms-ham (real messages, benign)', join(cache, 'sms', 'ham.jsonl')],
    ['sms-spam (informational)', join(cache, 'sms', 'spam.jsonl')],
  );
// The scam rules on long human-written texts (news, essays, stories): what the extension's
// quiet badge would do on ordinary pages. Needs the text datasets (`pnpm eval:fetch --full`).
{
  const items = [];
  for (const set of ['ghostbuster', 'fdgpt', 'liang']) {
    const path = join(cache, set, 'text.jsonl');
    if (!existsSync(path)) continue;
    for (const item of await loadJsonl(path))
      if (item.truth === 'human')
        items.push({
          id: item.id,
          truth: 'benign' as const,
          category: `${set}/${item.subgroup ?? 'text'}`,
          source: item.source,
          text: item.text,
        });
  }
  if (items.length > 0) {
    const r = evaluateScam(
      'long human texts (news, essays, stories; benign)',
      SCAM_ENGINE_VERSION,
      items,
    );
    json.scam.push(r);
    const high = r.falseAlarms.filter((f) => f.risk === 'high').length;
    sections.push(
      scamToMarkdown(r).split('\n**False alarms')[0]!,
      `Of the ${r.falseAlarms.length} flagged texts, ${high} are "high" (the red mark) and ${r.falseAlarms.length - high} "medium" (the amber mark).`,
      '',
    );
  }
}

for (const [name, path] of scamSets) {
  const r = evaluateScam(name, SCAM_ENGINE_VERSION, await loadScamJsonl(path));
  json.scam.push(r);
  // Spam lists are long and not actionable; keep only the summary table.
  const md = scamToMarkdown(r);
  sections.push(name.startsWith('sms-spam') ? md.split('\n**Missed')[0]! : md);
}

const outDir = join(root, 'reports');
await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'report.json'), JSON.stringify(json, null, 2) + '\n');
const md = sections.join('\n');
await writeFile(join(outDir, 'report.md'), md);
console.log(md);
console.log(`Wrote eval/reports/report.{md,json}`);
