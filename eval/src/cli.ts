import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { ENGINE_VERSION, SCAM_ENGINE_VERSION, TEXT_STATS_MODEL } from '@isitreal/core';
import { crossDomain, crossDomainMarkdown, type CrossDomainRow } from './cross-domain.js';
import { loadJsonl } from './dataset.js';
import { DETECTORS, randomBaseline } from './detectors.js';
import { evaluate, toMarkdown, type DetectorReport } from './run.js';
import { evaluateScam, loadScamJsonl, scamToMarkdown, type ScamReport } from './scam.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({ options: { alpha: { type: 'string', default: '0.01' } } });
const alpha = Number(values.alpha);
const cache = join(root, 'datasets', '.cache');

const sections: string[] = [
  '# Evaluation report',
  '',
  `Engine ${ENGINE_VERSION}, ${SCAM_ENGINE_VERSION}, alpha = ${alpha}. Generated by \`pnpm eval\`.`,
  '',
];
const json: { text: DetectorReport[]; scam: ScamReport[]; crossDomain?: CrossDomainRow[] } = {
  text: [],
  scam: [],
};

// Text detectors.
const textSets: [string, string, typeof DETECTORS][] = [
  ['toy', join(root, 'datasets', 'toy', 'text.jsonl'), [randomBaseline]],
];
const fd = join(cache, 'fdgpt', 'text.jsonl');
if (existsSync(fd)) textSets.push(['fdgpt-gpt3to4', fd, DETECTORS.filter((d) => d.calibrated)]);
else
  sections.push('> fdgpt dataset not downloaded; run `pnpm eval:fetch` for real text results.', '');
for (const [name, path, dets] of textSets) {
  const items = await loadJsonl(path);
  const reports = dets.map((d) => evaluate(d, name, items, alpha));
  json.text.push(...reports);
  sections.push(toMarkdown(reports));
  if (name.startsWith('fdgpt')) {
    const rows = crossDomain(items, TEXT_STATS_MODEL.minWords);
    json.crossDomain = rows;
    sections.push(crossDomainMarkdown(rows));
  }
}

// Scam rules.
const scamSets: [string, string][] = [
  ['scam-dev', join(root, 'datasets', 'scam', 'dev.jsonl')],
  ['scam-test (frozen)', join(root, 'datasets', 'scam', 'test.jsonl')],
];
if (existsSync(join(cache, 'sms')))
  scamSets.push(
    ['sms-ham (real messages, benign)', join(cache, 'sms', 'ham.jsonl')],
    ['sms-spam (informational)', join(cache, 'sms', 'spam.jsonl')],
  );
for (const [name, path] of scamSets) {
  const r = evaluateScam(name, SCAM_ENGINE_VERSION, await loadScamJsonl(path));
  json.scam.push(r);
  // Spam lists are long and not actionable; keep only the summary table.
  const md = scamToMarkdown(r);
  sections.push(name.startsWith('sms-spam') ? md.split('\n**Missed')[0]! : md);
}

const outDir = join(root, 'reports');
await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'report.json'), JSON.stringify(json, null, 2) + '\n');
const md = sections.join('\n');
await writeFile(join(outDir, 'report.md'), md);
console.log(md);
console.log(`Wrote eval/reports/report.{md,json}`);
