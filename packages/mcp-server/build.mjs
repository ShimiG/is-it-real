/**
 * Bundles the MCP server into plugin/server/server.mjs (one file, no install needed), copies the
 * C2PA trust list next to it, and writes THIRD_PARTY_NOTICES.md for the bundled packages.
 * Native libraries (@contentauth/c2pa-node, onnxruntime-node, sharp) and model files are NOT
 * bundled: the server loads them at run time from the plugin's data folder (src/load.ts).
 */
import { build } from 'esbuild';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const out = join(root, 'plugin', 'server');

await rm(out, { recursive: true, force: true });
await mkdir(join(out, 'trust'), { recursive: true });

const result = await build({
  entryPoints: [join(here, 'src', 'main.ts')],
  outfile: join(out, 'server.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['@contentauth/c2pa-node', 'onnxruntime-node'],
  // Some bundled dependencies are CommonJS and call require() for Node built-ins.
  banner: {
    js: "import { createRequire as __isitrealCreateRequire } from 'node:module'; const require = __isitrealCreateRequire(import.meta.url);",
  },
  legalComments: 'none',
  metafile: true,
  absWorkingDir: here,
  logLevel: 'warning',
});

await copyFile(
  join(root, 'packages', 'c2pa-node', 'trust', 'C2PA-TRUST-LIST.pem'),
  join(out, 'trust', 'C2PA-TRUST-LIST.pem'),
);
await copyFile(
  join(root, 'packages', 'c2pa-node', 'trust', 'README.md'),
  join(out, 'trust', 'README.md'),
);

// Third-party notices: every package that ended up in the bundle, with its licence.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = input.match(/node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?((?:@[^/]+\/)?[^/]+)\//);
  if (!m) continue;
  const name = m[1];
  if (packages.has(name)) continue;
  const pkgDir = input.slice(
    0,
    input.indexOf(`node_modules/${name}/`) + `node_modules/${name}/`.length,
  );
  try {
    const pkg = JSON.parse(await readFile(resolve(here, pkgDir, 'package.json'), 'utf8'));
    packages.set(name, {
      version: pkg.version,
      license: pkg.license ?? 'see package',
      repo: pkg.repository?.url ?? pkg.repository ?? '',
    });
  } catch {
    packages.set(name, { version: '?', license: 'unknown', repo: '' });
  }
}
const rows = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b));
await writeFile(
  join(out, 'THIRD_PARTY_NOTICES.md'),
  [
    '# Third-party code in server.mjs',
    '',
    'Generated by packages/mcp-server/build.mjs. The bundle contains these packages, each under its own licence:',
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
    ...rows.map(([n, p]) => `| ${n} | ${p.version} | ${p.license} |`),
    '',
    'Loaded at run time, not bundled: @contentauth/c2pa-node (MIT), onnxruntime-node (MIT), sharp (Apache-2.0).',
    '',
    'Model files downloaded on first use, not bundled: the picture model (Community Forensics low-quality fine-tune, MIT) and the photo gate encoder (OpenAI CLIP ViT-B/32 image encoder, MIT).',
    '',
  ].join('\n'),
);
const size = (await readFile(join(out, 'server.mjs'))).length;
console.log(
  `plugin/server/server.mjs ${(size / 1024).toFixed(0)} KB, ${rows.length} bundled packages`,
);
