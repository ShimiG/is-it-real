/**
 * Builds the extension into dist/: one bundle per part (background worker, page reader, engine
 * page, side panel), plus the manifest and static files. Load dist/ in Chrome with
 * chrome://extensions > Developer mode > Load unpacked.
 */
import { build } from 'esbuild';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'dist');
const pkg = JSON.parse(await readFile(join(here, 'package.json'), 'utf8'));

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const common = {
  bundle: true,
  // ONNX Runtime Web: load its WebAssembly glue from files in the package instead of code
  // generated at run time, which Chrome does not allow in extensions.
  conditions: ['onnxruntime-web-use-extern-wasm'],
  target: 'chrome120',
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
};
// Extension pages and the service worker load ES modules; a content script cannot.
const pages = await build({
  ...common,
  format: 'esm',
  metafile: true,
  entryPoints: {
    background: join(here, 'src/background.ts'),
    offscreen: join(here, 'src/offscreen/main.ts'),
    sidepanel: join(here, 'src/sidepanel/main.ts'),
  },
  outdir: out,
});
const content = await build({
  ...common,
  format: 'iife',
  metafile: true,
  entryPoints: { content: join(here, 'src/content/main.ts') },
  outdir: out,
});

const manifest = JSON.parse(await readFile(join(here, 'manifest.json'), 'utf8'));
manifest.version = pkg.version;
await writeFile(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
await cp(join(here, 'src/sidepanel/index.html'), join(out, 'sidepanel.html'));
await cp(join(here, 'src/sidepanel/style.css'), join(out, 'sidepanel.css'));
await cp(join(here, 'src/offscreen/index.html'), join(out, 'offscreen.html'));
await cp(join(here, 'public'), out, { recursive: true });

// Content Credentials: the official library's WebAssembly file and the official trust list
// (the same file the plugin ships; see packages/c2pa-node/trust/README.md).
const require = createRequire(import.meta.url);
await cp(require.resolve('@contentauth/c2pa-wasm/c2pa.wasm'), join(out, 'c2pa.wasm'));
// The model runtime (ONNX Runtime Web, CPU build). The model files themselves are not part of
// the extension: they are downloaded once when the person switches the picture check on.
await mkdir(join(out, 'ort'), { recursive: true });
for (const file of ['ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs'])
  await cp(require.resolve(`onnxruntime-web/${file}`), join(out, 'ort', file));
await mkdir(join(out, 'trust'), { recursive: true });
await cp(
  join(here, '..', '..', 'packages', 'c2pa-node', 'trust', 'C2PA-TRUST-LIST.pem'),
  join(out, 'trust', 'C2PA-TRUST-LIST.pem'),
);
// Third-party notices: every package that ended up in the bundles or is shipped as a file.
const packages = new Map();
const inputs = [...Object.keys(pages.metafile.inputs), ...Object.keys(content.metafile.inputs)];
for (const input of inputs) {
  const m = input.match(/node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?((?:@[^/]+\/)?[^/]+)\//);
  if (!m || packages.has(m[1])) continue;
  const dir = input.slice(
    0,
    input.indexOf(`node_modules/${m[1]}/`) + `node_modules/${m[1]}/`.length,
  );
  try {
    const found = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
    packages.set(m[1], { version: found.version, license: found.license ?? 'see package' });
  } catch {
    packages.set(m[1], { version: '?', license: 'unknown' });
  }
}
const rows = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b));
await writeFile(
  join(out, 'THIRD_PARTY_NOTICES.md'),
  [
    '# Third-party code in this extension',
    '',
    'Generated by apps/extension/build.mjs. The extension contains these packages, each under its own licence:',
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
    ...rows.map(([n, p]) => `| ${n} | ${p.version} | ${p.license} |`),
    '',
    'Shipped as files: `c2pa.wasm` (the official C2PA library, from @contentauth/c2pa-wasm) and `ort/` (ONNX Runtime Web, from onnxruntime-web), under the licences above. `trust/C2PA-TRUST-LIST.pem` is the official C2PA trust list.',
    '',
    'Not part of the extension, downloaded once when the picture check is switched on: the picture model (Community Forensics low-quality fine-tune, MIT) and the photo gate encoder (OpenAI CLIP ViT-B/32 image encoder, MIT).',
    '',
  ].join('\n'),
);
console.log(`apps/extension/dist built (version ${pkg.version})`);
